"""tokens.json -> tokens.css (same names as Figma's WEB code syntax: color/bg/page -> --bg-page)."""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__))
d = json.load(open(os.path.join(HERE, 'tokens.json')))['resolved']
def name(n): return '--' + n.replace('color/', '').replace('/', '-')
light = '\n'.join(f'  {name(n)}: {v["Light"]};' for n, v in d.items())
dark = '\n'.join(f'  {name(n)}: {v["Dark"]};' for n, v in d.items())
static = """  /* overlays */
  --bg-scrim: rgb(18 24 19 / 0.55);
  --bg-page-clear: rgb(244 253 245 / 0);
  /* spacing */
  --spacing-xxs: 4px; --spacing-xs: 8px; --spacing-sm: 12px; --spacing-md: 16px;
  --spacing-lg: 20px; --spacing-xl: 24px; --spacing-xxl: 32px; --spacing-xxxl: 48px;
  /* radius */
  --radius-sm: 8px; --radius-md: 12px; --radius-lg: 16px; --radius-xl: 24px; --radius-full: 999px;
  /* size */
  --size-touch-target: 48px; --size-button: 48px; --size-edge: 4px;
  /* type: Atkinson Hyperlegible Next (bundle the woff2, OFL) */
  --font: "Atkinson Hyperlegible Next", system-ui, sans-serif;
  --type-hero: 800 80px/80px var(--font);
  --type-display-l: 800 48px/56px var(--font);  --type-display-m: 800 36px/44px var(--font);
  --type-headline-l: 700 26px/32px var(--font); --type-headline-m: 700 22px/28px var(--font);
  --type-title-l: 700 18px/24px var(--font);    --type-title-m: 600 16px/22px var(--font);
  --type-body-l: 500 16px/24px var(--font);     --type-body-m: 400 15px/22px var(--font);
  --type-body-s: 400 13px/18px var(--font);
  --type-label-l: 700 15px/20px var(--font);    --type-label-m: 600 13px/18px var(--font);
  --type-label-s: 700 12px/16px var(--font);    /* + letter-spacing: 0.06em; uppercase */
  --type-label-stamp: 700 18px/22px var(--font);
  --type-question: 500 19px/28px var(--font);
  /* motion */
  --dur-fast: 90ms; --dur-short: 160ms; --dur-medium: 240ms; --dur-long: 450ms; --dur-count: 700ms;
  --ease-standard: cubic-bezier(.2,0,0,1); --ease-emphasized: cubic-bezier(.05,.7,.1,1);"""
css = f"""/* GENERATED by tools/tokens/gen_css.py from tokens.json — do not edit by hand. */
/* Light = "Naija Green · Day", Dark = "Adire Night". Green/mint = action, gold = proof, orange = gap, red = wrong. */
/* Theme follows the OS; data-theme="light|dark" on <html> or any element overrides it. .pin-light keeps proof cards light. */
:root {{
{light}
{static}
  color-scheme: light;
}}
@media (prefers-color-scheme: dark) {{
  :root:not([data-theme]) {{
{dark}
    --bg-scrim: rgb(0 5 20 / 0.7);
    --bg-page-clear: rgb(6 15 53 / 0);
    color-scheme: dark;
  }}
}}
[data-theme="light"], .pin-light {{
{light}
  --bg-scrim: rgb(18 24 19 / 0.55);
  --bg-page-clear: rgb(244 253 245 / 0);
  color-scheme: light;
}}
[data-theme="dark"] {{
{dark}
  --bg-scrim: rgb(0 5 20 / 0.7);
  --bg-page-clear: rgb(6 15 53 / 0);
  color-scheme: dark;
}}
@media (prefers-reduced-motion: reduce) {{
  :root {{ --dur-fast: 0ms; --dur-short: 0ms; --dur-medium: 0ms; --dur-long: 0ms; --dur-count: 0ms; }}
}}
"""
open(os.path.join(HERE, '..', '..', 'src', 'styles', 'tokens.css'), 'w').write(css)
print(len(d), 'colour tokens ->', 'tokens.css')
